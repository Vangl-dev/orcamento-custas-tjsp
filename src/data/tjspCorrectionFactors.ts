function parseFactor(value: string) {
  if (value === '----------') return null

  return Number(value.replace(/\./g, '').replace(',', '.'))
}

const baseCorrectionFactors: CorrectionFactor[] = rawBlocks.flatMap(
  ({ years, rows }) =>
    monthNames.flatMap((monthName, monthIndex) =>
      years.flatMap((year, yearIndex) => {
        const factor = parseFactor(rows[monthName]?.[yearIndex] ?? '')

        if (!factor) return []

        return {
          year,
          month: monthIndex + 1,
          factor,
        }
      }),
    ),
)

export const TJSP_CORRECTION_FACTORS: CorrectionFactor[] = Array.from(
  [
    ...baseCorrectionFactors,
    ...MANUAL_TJSP_CORRECTION_FACTORS,
  ].reduce((map, item) => {
    map.set(`${item.year}-${item.month}`, item)

    return map
  }, new Map<string, CorrectionFactor>()).values(),
).sort((a, b) => a.year - b.year || a.month - b.month)

